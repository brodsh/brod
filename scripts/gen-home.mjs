// Generate src/home.ts from server/src/home.html, the landing page at / for people who are not signed in.
// The Rust server embeds the HTML file with include_str!; the Worker, the Vercel bundle and the tests all import this
// module, so no bundler needs an HTML loader. test-node/home.test.ts fails if the two drift apart.
// The link preview picture, server/src/og.png (npm run gen:og), is copied in too, as base64, for /og.png.
// Usage: npm run gen:home   (after editing server/src/home.html or server/src/og.png)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('server/src/home.html', 'utf8');
const etag = `"${createHash('sha256').update(html).digest('hex').slice(0, 16)}"`;
const og = readFileSync('server/src/og.png');
const ogEtag = `"${createHash('sha256').update(og).digest('hex').slice(0, 16)}"`;
writeFileSync('src/home.ts', `// Generated by scripts/gen-home.mjs from server/src/home.html. Do not edit; run npm run gen:home.
export const HOME_HTML = ${JSON.stringify(html)};
export const HOME_ETAG = ${JSON.stringify(etag)};
export const OG_PNG_BASE64 = ${JSON.stringify(og.toString('base64'))};
export const OG_PNG_ETAG = ${JSON.stringify(ogEtag)};
`);
console.log(`Wrote src/home.ts (${html.length} characters, etag ${etag})`);
