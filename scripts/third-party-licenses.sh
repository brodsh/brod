#!/usr/bin/env bash
# Regenerate THIRD_PARTY_LICENSES.md: every Rust crate compiled into the brod and brod-runtime binaries, with its
# license text, and the third-party software in the Docker images. Needs cargo-about (cargo install cargo-about).
# Usage: scripts/third-party-licenses.sh            (from the repository root)
set -euo pipefail
cd "$(dirname "$0")/.."
workerd=$(node -p "require('./package.json').devDependencies.workerd")
out=THIRD_PARTY_LICENSES.md
{
  cat <<HEAD
# Third-party licenses

Brod is licensed under AGPL-3.0-only (see LICENSE). It includes the third-party software listed below. Each is
used under its own license; every license here is compatible with AGPL-3.0 (checked in CI by \`cargo deny\`).

Generated by \`scripts/third-party-licenses.sh\`. Do not edit by hand.

## Docker images

| Component | Image | License |
|---|---|---|
| [workerd](https://github.com/cloudflare/workerd) ${workerd} | \`brod-runtime\` | Apache-2.0 |
| [distroless/cc-debian12](https://github.com/GoogleContainerTools/distroless) base | \`brod\`, \`brod-runtime\` | Apache-2.0 (Debian packages under their own licenses, listed in the image under /usr/share/doc) |

The Node packages in package.json are used only to run the tests and are not part of any image.

## Rust crates in \`brod\` (server/)

HEAD
  cargo about generate --manifest-path server/Cargo.toml -c licenses/about.toml licenses/about.hbs
  printf '\n## Rust crates in `brod-runtime` (deploy/runtime/supervisor/)\n\n'
  cargo about generate --manifest-path deploy/runtime/supervisor/Cargo.toml -c licenses/about.toml licenses/about.hbs
} > "$out"
echo "Wrote $out"
