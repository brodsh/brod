-- Brod schema for Postgres: the same tables, columns and names as migrations/0001_init.sql (read that file for what each
-- table is for). Only the dialect differs: timestamps are epoch milliseconds in BIGINT, AUTOINCREMENT ids are identity
-- columns (BY DEFAULT, so `brod migrate-to-postgres` can keep the ids it copies), and text that the server sorts by
-- uses the "C" collation, which orders by code point as SQLite does.

CREATE TABLE users (
  id TEXT PRIMARY KEY, email TEXT COLLATE "C" NOT NULL UNIQUE, name TEXT NOT NULL DEFAULT '',
  email_verified_at BIGINT, terms_accepted_at BIGINT, created_at BIGINT NOT NULL
);

CREATE TABLE workspaces (
  id TEXT PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, plan TEXT NOT NULL DEFAULT 'free',
  color TEXT NOT NULL DEFAULT '#1f6f4a', icon TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL
);

CREATE TABLE members (
  workspace_id TEXT NOT NULL REFERENCES workspaces(id), user_id TEXT NOT NULL REFERENCES users(id),
  role TEXT NOT NULL CHECK (role IN ('admin', 'builder', 'member', 'guest')), created_at BIGINT NOT NULL,
  PRIMARY KEY (workspace_id, user_id)
);
CREATE INDEX members_user ON members(user_id);

CREATE TABLE groups (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), name TEXT COLLATE "C" NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE (workspace_id, name)
);
CREATE TABLE group_members (
  group_id TEXT NOT NULL REFERENCES groups(id), user_id TEXT NOT NULL REFERENCES users(id), PRIMARY KEY (group_id, user_id)
);
CREATE INDEX group_members_user ON group_members(user_id);

CREATE TABLE invites (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), email TEXT NOT NULL, role TEXT NOT NULL,
  app_id TEXT, app_role TEXT, hash TEXT NOT NULL UNIQUE, invited_by TEXT NOT NULL,
  created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, used_at BIGINT, revoked_at BIGINT
);
CREATE INDEX invites_workspace ON invites(workspace_id, created_at);

CREATE TABLE tokens (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), user_id TEXT NOT NULL REFERENCES users(id),
  name TEXT NOT NULL, hash TEXT NOT NULL UNIQUE, created_at BIGINT NOT NULL, last_used_at BIGINT, revoked_at BIGINT
);

CREATE TABLE apps (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), owner_id TEXT NOT NULL REFERENCES users(id),
  slug TEXT NOT NULL UNIQUE, name TEXT COLLATE "C" NOT NULL, title TEXT NOT NULL DEFAULT '', welcome TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'live',
  access TEXT NOT NULL DEFAULT 'private' CHECK (access IN ('private', 'people', 'workspace', 'signed_in', 'public')),
  roles TEXT NOT NULL DEFAULT '["owner","editor","viewer"]', live_version BIGINT, created_at BIGINT NOT NULL
);
CREATE INDEX apps_workspace ON apps(workspace_id);

CREATE TABLE grants (
  app_id TEXT NOT NULL REFERENCES apps(id), subject TEXT NOT NULL, role TEXT NOT NULL, created_at BIGINT NOT NULL,
  PRIMARY KEY (app_id, subject)
);

CREATE TABLE versions (
  app_id TEXT NOT NULL REFERENCES apps(id), n BIGINT NOT NULL, note TEXT NOT NULL, actor TEXT NOT NULL,
  file_count BIGINT NOT NULL, bytes BIGINT NOT NULL, created_at BIGINT NOT NULL, PRIMARY KEY (app_id, n)
);
CREATE TABLE uploads (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, user_id TEXT NOT NULL, actor TEXT NOT NULL, app_slug TEXT, name TEXT,
  note TEXT NOT NULL, expires_at BIGINT NOT NULL, used_at BIGINT
);

CREATE TABLE login_links (
  hash TEXT PRIMARY KEY, email TEXT NOT NULL, return_to TEXT NOT NULL, created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL, used_at BIGINT
);
CREATE INDEX login_links_email ON login_links(email, created_at);

CREATE TABLE sessions (
  hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), app_id TEXT, parent TEXT,
  created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, revoked_at BIGINT
);
CREATE INDEX sessions_parent ON sessions(parent);

CREATE TABLE app_codes (
  hash TEXT PRIMARY KEY, app_id TEXT NOT NULL, user_id TEXT NOT NULL, parent TEXT NOT NULL, expires_at BIGINT NOT NULL, used_at BIGINT
);

CREATE TABLE confirmations (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, app_id TEXT, kind TEXT NOT NULL, payload TEXT NOT NULL, summary TEXT NOT NULL,
  requested_by TEXT NOT NULL, created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, done_at BIGINT, done_by TEXT
);

CREATE TABLE reports (
  id TEXT PRIMARY KEY, app_id TEXT NOT NULL, reporter TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open'
);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id TEXT NOT NULL, app_id TEXT, at BIGINT NOT NULL,
  actor TEXT NOT NULL, action TEXT NOT NULL, detail TEXT NOT NULL
);
CREATE INDEX events_app ON events(app_id, at);
CREATE INDEX events_workspace ON events(workspace_id, action, at);
